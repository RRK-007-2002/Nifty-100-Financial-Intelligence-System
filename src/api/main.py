def _register_routers(
    fastapi_app: FastAPI,
    module_names: List[str],
) -> None:
    """
    Dynamically import and register API routers.

    Each router module is expected to expose:

        router = APIRouter(...)

    Routers that have not yet been created are skipped.

    Parameters
    ----------
    fastapi_app:
        FastAPI application instance.

    module_names:
        Router module names under src.api.routers.
    """

    for module_name in module_names:

        module_path = f"src.api.routers.{module_name}"

        try:
            module = importlib.import_module(module_path)

        except ModuleNotFoundError as exc:

            # Only skip the router if the router module itself
            # does not exist.
            if exc.name == module_path:
                print(
                    f"[INFO] Router not implemented yet: "
                    f"{module_path}"
                )
                continue

            # If the router exists but one of its dependencies
            # is missing, expose the actual error.
            raise

        if not hasattr(module, "router"):
            print(
                f"[WARNING] Router module has no 'router': "
                f"{module_path}"
            )
            continue

        fastapi_app.include_router(
            module.router,
            prefix="/api/v1",
        )

        print(
            f"[INFO] Registered router: "
            f"/api/v1/{module_name}"
        )



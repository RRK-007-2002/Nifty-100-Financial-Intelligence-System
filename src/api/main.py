@app.middleware("http")
async def log_requests(
    request: Request,
    call_next: Callable[[Request], Awaitable[Response]],
) -> Response:
    """
    Log HTTP method, request path, status code and latency.

    Parameters
    ----------
    request:
        Incoming HTTP request.

    call_next:
        Next middleware / endpoint in the FastAPI pipeline.

    Returns
    -------
    Response
        Response generated by the downstream endpoint.
    """

    start = time.perf_counter()

    response = await call_next(request)

    latency_ms = (time.perf_counter() - start) * 1000

    print(
        f"[{request.method}] "
        f"[{request.url.path}] "
        f"[{response.status_code}] "
        f"[{latency_ms:.2f}ms]"
    )

    return response



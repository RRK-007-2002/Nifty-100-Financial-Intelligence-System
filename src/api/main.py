def get_db_row_counts(
    db_path: Path,
    tables: List[str],
) -> Dict[str, int]:
    """
    Return row counts for the requested database tables.

    If a table does not exist, its count is reported as -1.

    Parameters
    ----------
    db_path:
        SQLite database path.

    tables:
        List of table names.

    Returns
    -------
    Dict[str, int]
        Mapping of table name -> row count.
    """

    counts: Dict[str, int] = {}

    if not db_path.exists():
        return {table: -1 for table in tables}

    with sqlite3.connect(str(db_path)) as conn:
        cursor = conn.cursor()

        for table in tables:

            try:
                # Table names come only from SCHEMA_TABLES,
                # not from user input.
                cursor.execute(
                    f"SELECT COUNT(*) FROM [{table}]"
                )

                result = cursor.fetchone()

                counts[table] = int(result[0]) if result else 0

            except sqlite3.OperationalError:
                counts[table] = -1

    return counts


def check_database_connection(db_path: Path) -> bool:
    """
    Check whether the SQLite database can be opened successfully.

    Returns
    -------
    bool
        True if the database can be opened, otherwise False.
    """

    if not db_path.exists():
        return False

    try:
        with sqlite3.connect(str(db_path)) as conn:
            conn.execute("SELECT 1")

        return True

    except sqlite3.Error:
        return False



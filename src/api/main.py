@app.get(
    "/api/v1/health",
    tags=["Health"],
)
def get_health() -> Dict[str, object]:
    """
    Health check endpoint.

    Returns database connectivity, table row counts,
    API uptime and application version.
    """

    db_connected = check_database_connection(DB_PATH)

    return {
        "status": "ok" if db_connected else "degraded",
        "database": {
            "connected": db_connected,
            "path": str(DB_PATH),
        },
        "db_row_counts": get_db_row_counts(
            DB_PATH,
            SCHEMA_TABLES,
        ),
        "uptime_seconds": round(
            time.time() - APP_START_TIME,
            2,
        ),
        "version": APP_VERSION,
    }


